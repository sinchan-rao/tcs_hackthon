// Current active language (default: English)
let currentLang = localStorage.getItem('finchat_lang') || 'en';

/**
 * Get a translation string for the current language.
 * Falls back to English if the key is not found.
 */
function t(key) {
    return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key] !== undefined
        ? TRANSLATIONS[currentLang][key]
        : (TRANSLATIONS['en'][key] !== undefined ? TRANSLATIONS['en'][key] : key));
}

/**
 * Set the active language and re-render all static UI text.
 */
function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    currentLang = lang;
    localStorage.setItem('finchat_lang', lang);
    applyLanguageToDOM();
}

/**
 * Apply translations to all static DOM elements.
 */
function applyLanguageToDOM() {
    _setText('login-heading', t('loginHeading'));
    _setText('login-subtitle', t('loginSubtitle'));
    _setText('label-profile', t('selectProfile'));
    _setOptionText('guest', t('guestMode'));
    _setText('label-pin', t('enterPin'));
    _setText('login-btn-text', t('accessBtn'));
    _setText('hackathon-tag-text', t('mockTag'));

    _setText('header-title', t('headerTitle'));
    _setText('new-conversation-btn-text', t('newConversation'));

    const chatInput = document.getElementById('chat-input');
    if (chatInput) chatInput.placeholder = t('chatPlaceholder');

    _setText('modal-cancel-btn', t('modalCancel'));
    _setText('otp-label', t('enterOtpLabel'));

    // Language switcher active state
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === currentLang);
    });
}

function _setText(id, text) {
    const el = document.getElementById(id);
    if (el) el.textContent = text;
}

function _setOptionText(value, text) {
    const select = document.getElementById('customer-select');
    if (!select) return;
    const opt = select.querySelector(`option[value="${value}"]`);
    if (opt) opt.textContent = text;
}
